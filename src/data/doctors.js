const toLocalISO = (date) => {
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${date.getFullYear()}-${month}-${day}`;
};

export const resolveDoctorSlots = (doctor) => {
  if (!doctor?.slots?.length) return [];

  return doctor.slots.map((slot) => {
    const date = new Date();
    date.setHours(0, 0, 0, 0);
    date.setDate(date.getDate() + slot.offset);

    let label = date.toLocaleDateString('en-US', {
      weekday: 'long',
      month: 'short',
      day: 'numeric',
    });
    if (slot.offset === 0) label = 'Today';
    if (slot.offset === 1) label = 'Tomorrow';

    return {
      date: toLocalISO(date),
      label,
      times: slot.times,
    };
  });
};

